"""Форматы файлового отчёта (артефакт сценария / output_dir).

Не enum, а обычный класс с текстовыми константами: ``report_formats`` в
конфиге можно задать и через код (``ReportType.HTML``), и просто строкой,
например из переменной окружения в CI (``"html"``) — значения сравниваются
без учёта регистра, так что не требуется явный маппинг строка → константа.
"""

__all__ = ("ReportType",)


class ReportType:
    """Пространство имён текстовых констант формата отчёта."""

    HTML = "html"
    MARKDOWN = "markdown"
