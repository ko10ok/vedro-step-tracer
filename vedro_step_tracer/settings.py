"""
Изменяемые в рантайме настройки трейсера.

Значения читаются форматтерами через модуль (``settings.MAX_STR_LEN``), а не
импортируются по имени: плагин переопределяет их из конфига при старте, и
импорт по имени зафиксировал бы значение по умолчанию.
"""

from typing import Set

__all__ = ("MAX_STR_LEN", "MAX_LINE_LEN", "FILTERED_KEYS",
           "set_max_str_len", "set_max_line_len",)

# Максимальная длина строкового значения перед сокращением в отчётах.
# Применяется к каждой физической строке отдельно.
MAX_STR_LEN: int = 1000

# Максимальная длина одной физической строки в выводе нестандартного объекта
# (рендер через __str__/repr/rich, например HTTP-трейс). Переносы строк
# разделяют: каждая линия режется независимо, структура сохраняется.
MAX_LINE_LEN: int = 1000

# Служебные имена, которые никогда не попадают в дерево переменных.
FILTERED_KEYS: Set[str] = {"self", "__class__", "__builtins__"}


def set_max_str_len(value: int) -> None:
    """Переопределить лимит длины строк (вызывается плагином из конфига)."""
    global MAX_STR_LEN
    MAX_STR_LEN = value


def set_max_line_len(value: int) -> None:
    """Переопределить лимит длины физической строки объекта (из конфига)."""
    global MAX_LINE_LEN
    MAX_LINE_LEN = value
