"""События (статусы) сценария, по которым пишется файловый отчёт.

Не enum, а обычный класс с текстовыми константами: ``save_to_dir`` можно
задавать и через код (``TestStatus.FAILED``), и просто строкой из конфига
или переменной окружения — значения сравниваются без учёта регистра.
"""

__all__ = ("TestStatus",)


class TestStatus:
    """Пространство имён текстовых констант статуса сценария."""

    FAILED = "failed"
    PASSED = "passed"
